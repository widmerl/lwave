#!/usr/bin/env python3
"""Generates the API part of docs/REFERENCE.md from the `///` doc comments in
the firmware headers, plus the settings table from settings.cpp.

    python3 firmware/tools/gen_reference.py            # rewrite docs/REFERENCE.md
    python3 firmware/tools/gen_reference.py --check    # list undocumented declarations

The hand-written part of REFERENCE.md (everything above the marker line) is kept.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FW = os.path.join(ROOT, "firmware")
DOC = os.path.join(ROOT, "docs", "REFERENCE.md")
MARKER = "<!-- API REFERENCE: generated by firmware/tools/gen_reference.py, do not edit below -->"

HEADER_DIRS = [
    ("Portable core (lib/lwave/src/lwave)", os.path.join(FW, "lib", "lwave", "src", "lwave")),
    ("DSP building blocks (lib/lwave/src/lwave/dsp)", os.path.join(FW, "lib", "lwave", "src", "lwave", "dsp")),
    ("Teensy layer (src)", os.path.join(FW, "src")),
]

TYPE_RE = re.compile(r"^\s*(?:template\s*<[^>]*>\s*)?(class|struct|enum class|enum)\s+(\w+)")


def file_summary(lines):
    out = []
    for ln in lines:
        s = ln.strip()
        if s.startswith("#pragma") or not s.startswith("//") or s.startswith("///"):
            break
        out.append(s.lstrip("/").strip())
    text = " ".join(out)
    text = re.sub(r"^L-wave firmware( \(Teensy only\))? — ", "", text)
    return text[:1].upper() + text[1:]


def clean_decl(decl):
    decl = re.sub(r"\s+", " ", decl).strip()
    decl = re.sub(r"\s*\{.*$", "", decl)  # drop inline bodies
    decl = decl.rstrip(";").strip()
    decl = re.sub(r"\s*=\s*0$", "", decl)
    return decl


def parse_header(path):
    """Returns (summary, items). Item: (kind, signature, doc, depth)."""
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    items = []
    doc = []
    depth = 0
    i = 0
    while i < len(lines):
        ln = lines[i]
        s = ln.strip()
        if s.startswith("///") and not s.startswith("///<"):
            doc.append(s[3:].strip())
            i += 1
            continue
        if doc:
            # Gather the declaration that follows.
            decl = s
            j = i
            while not re.search(r"[;{]\s*$|[;{]\s*//.*$|\)\s*$", decl) and j + 1 < len(lines) and j - i < 6:
                j += 1
                decl += " " + lines[j].strip()
            m = TYPE_RE.match(decl)
            if s.startswith("#define"):
                kind = "macro"
            elif m:
                kind = m.group(1)
            elif "(" in decl:
                kind = "function"
            else:
                kind = "value"
            items.append((kind, clean_decl(decl), " ".join(doc), depth))
            doc = []
        # Trailing member docs: `float x = 0;  ///< text`
        m = re.match(r"^\s*(.+?);?\s*///<\s*(.*)$", ln)
        if m and not s.startswith("//"):
            items.append(("member", clean_decl(m.group(1)), m.group(2), depth))
        depth += ln.count("{") - ln.count("}")
        i += 1
    return file_summary(lines), items


def settings_table():
    path = os.path.join(FW, "lib", "lwave", "src", "lwave", "settings.cpp")
    hdr = os.path.join(FW, "lib", "lwave", "src", "lwave", "settings.h")
    defaults = {}
    for ln in open(hdr, encoding="utf-8"):
        m = re.match(r"\s*float (\w+) = ([-\d.]+)f;", ln)
        if m:
            defaults[m.group(1)] = m.group(2)
    rows = []
    for ln in open(path, encoding="utf-8"):
        m = re.match(r'\s*\{"(\w+)", &Settings::(\w+), ([^,]+), ([^,]+), "([^"]*)"\}', ln)
        if m:
            lo = m.group(3).replace("(float)", "").rstrip("f")
            hi = m.group(4).replace("(float)", "").rstrip("f")
            rows.append(f"| `{m.group(1)}` | {defaults.get(m.group(2), '?')} | {lo} … {hi} | {m.group(5)} |")
    return "| Setting | Default | Range | Meaning |\n| --- | --- | --- | --- |\n" + "\n".join(rows)


def generate():
    out = [MARKER, "", "## API reference", "",
           "Generated from the `///` comments in the headers. Every class, function and field is listed in the order it appears in its header.",
           ""]
    out += ["### Settings (from settings.cpp)", "", settings_table(), ""]
    for title, d in HEADER_DIRS:
        out += [f"### {title}", ""]
        for name in sorted(os.listdir(d)):
            if not name.endswith(".h"):
                continue
            summary, items = parse_header(os.path.join(d, name))
            out += [f"#### `{name}`", "", summary, ""]
            for kind, sig, doc, depth in items:
                indent = "  " * min(depth, 2) if kind in ("member", "function", "value") and depth > 1 else ""
                if kind in ("class", "struct", "enum class", "enum"):
                    out += [f"- **{kind} `{sig.split(':')[0].replace(kind, '').strip()}`** — {doc}"]
                else:
                    out += [f"{indent}- `{sig}` — {doc}"]
            out.append("")
    return "\n".join(out) + "\n"


def check():
    """Lists public declarations in headers without a doc comment."""
    missing = 0
    for _, d in HEADER_DIRS:
        for name in sorted(os.listdir(d)):
            if not name.endswith(".h"):
                continue
            lines = open(os.path.join(d, name), encoding="utf-8").read().splitlines()
            private = False
            for i, ln in enumerate(lines):
                s = ln.strip()
                if s.startswith("private:"):
                    private = True
                elif s.startswith("public:") or s.startswith("};"):
                    private = False
                if private or not s or s.startswith("//") or "///<" in s or "override" in s:
                    continue
                looks_decl = re.match(r"^(?:static |inline |virtual |constexpr |explicit |const )*[\w:<>,\s\*&]+\s+\*?&?\w+\s*\(.*\)\s*(const)?\s*(;|\{)", s) \
                    or TYPE_RE.match(s)
                if looks_decl and not s.startswith(("return", "if", "for", "while", "switch", "case", "else")):
                    prev = lines[i - 1].strip() if i else ""
                    if prev.startswith("template") and i > 1:
                        prev = lines[i - 2].strip()
                    if not prev.startswith("///") and ln.startswith(("  ", "class", "struct", "enum", "inline", "float", "int", "void", "bool", "uint", "const")) is not None:
                        if ln[:1] != " " or ln.startswith("  ") and not ln.startswith("    "):
                            print(f"{name}:{i + 1}: {s}")
                            missing += 1
    print(f"{missing} undocumented declarations")
    return missing


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(1 if check() else 0)
    text = open(DOC, encoding="utf-8").read() if os.path.exists(DOC) else ""
    head = text.split(MARKER)[0].rstrip() + "\n\n" if MARKER in text else text
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(head + generate())
    print(f"wrote {DOC}")
